#!/usr/bin/env bash
# Builds one paste-able file for the Supabase SQL Editor: all migrations in order, then the shared seed.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=dist/orbit_setup.sql
{
  echo "-- ORBIT: complete database setup (generated by supabase/test/build-setup-sql.sh; do not edit by hand)."
  echo "-- Paste into Supabase > SQL Editor and run ONCE on a fresh project."
  for f in migrations/*.sql; do printf '\n-- ===== %s =====\n' "$(basename "$f")"; cat "$f"; done
  printf '\n-- ===== seed.sql (shared chapters) =====\n'; cat seed/seed.sql
} > "$OUT"
echo "wrote supabase/$OUT ($(wc -l < "$OUT") lines)"
